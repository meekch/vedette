/**
 * Regenerate the Meridian analysis snapshot with a real model call.
 *
 *   npm run analyze
 *
 * Reads the seeded evidence, runs the Analysis & Scoring Agent, validates the
 * output against `opportunitySetSchema`, and writes `seed/meridian/analysis.ts`.
 *
 * This script is the reason the committed snapshot is honest rather than
 * decorative: the snapshot's shape is not hand-maintained, it is whatever the
 * agent produces under the same schema, and this command replaces it.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { config } from "dotenv";
import { runAnalysis } from "../src/lib/ai/agents/analysis";
import { MERIDIAN_EVIDENCE } from "../seed/meridian/documents";
import { MERIDIAN_ORG, MERIDIAN_OBJECTIVES } from "../seed/meridian/profile";

config({ path: ".env.local" });

const OUTPUT_PATH = resolve(process.cwd(), "seed/meridian/analysis.ts");

const HEADER = `import type { OpportunitySet } from "@/lib/ai/schemas/opportunity";

/**
 * The scored-opportunity snapshot for the Meridian demo.
 *
 * GENERATED by \`npm run analyze\` — do not edit by hand; your changes will be
 * overwritten on the next run. Regenerating requires a chat-model key
 * (see README § Environment).
 *
 * Shipping a snapshot rather than calling the model on every page load keeps the
 * deployed demo free, fast, and incapable of failing in front of an audience.
 */
export const MERIDIAN_ANALYSIS: OpportunitySet = `;

async function main() {
  console.log(
    `Analysing ${MERIDIAN_EVIDENCE.length} evidence chunks for ${MERIDIAN_ORG.name}...`,
  );

  const { result, telemetry } = await runAnalysis({
    organizationName: MERIDIAN_ORG.name,
    organizationProfile: MERIDIAN_ORG.profile,
    statedObjectives: [...MERIDIAN_OBJECTIVES],
    chunks: MERIDIAN_EVIDENCE,
  });

  // Fail loudly on a dangling citation. A snapshot that references a chunk which
  // does not exist would render an empty evidence drawer — the single most
  // damaging failure this product can have, because it looks like it worked.
  const validIds = new Set(MERIDIAN_EVIDENCE.map((c) => c.id));
  const dangling = result.opportunities.flatMap((o) =>
    [...o.scores.flatMap((s) => s.evidenceIds), ...o.roiInputs.evidenceIds].filter(
      (id) => !validIds.has(id),
    ),
  );
  if (dangling.length > 0) {
    throw new Error(
      `Agent cited ${dangling.length} evidence id(s) that do not exist: ${[...new Set(dangling)].join(", ")}`,
    );
  }

  writeFileSync(
    OUTPUT_PATH,
    `${HEADER}${JSON.stringify(result, null, 2)};\n`,
    "utf8",
  );

  console.log(
    `\n✓ ${result.opportunities.length} opportunities, ${result.coverageGaps.length} coverage gaps`,
  );
  console.log(`  ${telemetry.provider}/${telemetry.modelId} · ${telemetry.latencyMs}ms`);
  console.log(`  written to ${OUTPUT_PATH}`);
  console.log(`\nRun \`npm test\` to verify the snapshot against the schema.`);
}

main().catch((err) => {
  console.error(`\n✗ ${err instanceof Error ? err.message : String(err)}`);
  process.exit(1);
});
